-- Was exec-once. Only runs on compositor start (not on reload).
hl.on("hyprland.start", function()
    hl.exec_cmd("nm-applet")
    hl.exec_cmd(os.getenv("HOME") .. "/.config/waybar/scripts/launch.sh")
    hl.exec_cmd("systemctl --user start hyprpolkitagent")
    hl.exec_cmd("swaync")
    -- Restores the last wallpaper (span/same); starts awww-daemon if needed.
    hl.exec_cmd("bash -c 'sleep 1 && " .. os.getenv("HOME") .. "/.config/hypr/scripts/wallpaper.sh restore'")

    -- Clipboard history (text + images) feeding cliphist
    hl.exec_cmd("wl-paste --type text --watch cliphist store")
    hl.exec_cmd("wl-paste --type image --watch cliphist store")

    -- Idle handling: lock after 10 min, screens off after 11 (see hypridle.conf)
    -- DISABLED until hyprlock is confirmed stable (it crashed once, see notes):
    -- hl.exec_cmd("hypridle")

    -- GTK/icon theme come from the theme switcher (re-applies the saved theme).
    hl.exec_cmd(os.getenv("HOME") .. "/.config/themes/theme-switch.sh restore")
    hl.exec_cmd([[bash -c 'sleep 3 && gsettings set org.gnome.desktop.interface cursor-size 18']])
end)

